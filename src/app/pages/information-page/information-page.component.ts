/** Файл, как он приходит из API */
export interface RawApiFile {
  name: string;      // "Правовая информация::Лицензия на медицинскую деятельность.pdf"
  url: string;
  size?: string;
  icon?: string;
}

/** Файл для отображения в списке документов раздела */
